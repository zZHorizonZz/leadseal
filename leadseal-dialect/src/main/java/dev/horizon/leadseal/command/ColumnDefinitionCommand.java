package dev.horizon.leadseal.command;

import dev.horizon.leadseal.Column;
import dev.horizon.leadseal.Dialect;
import dev.horizon.leadseal.ScriptWriter;
import dev.horizon.leadseal.Table;
import dev.horizon.leadseal.attribute.DefaultAttribute;
import dev.horizon.leadseal.attribute.IdentityAttribute;

/**
 * The definition of a column in {@code CREATE TABLE} and {@code ADD COLUMN}: the quoted name, the database type,
 * the collation, the identity, {@code NOT NULL} and the default.
 */
public class ColumnDefinitionCommand extends Command {

  private final Table definition;
  private final Column column;

  public ColumnDefinitionCommand(Table definition, Column column) {
    this.definition = definition;
    this.column = column;
  }

  /**
   * Returns the table of the column.
   *
   * @return the table of the column
   */
  public Table definition() {
    return definition;
  }

  /**
   * Returns the column.
   *
   * @return the column
   */
  public Column column() {
    return column;
  }

  @Override
  public void render(ScriptWriter sql) {
    Dialect dialect = sql.dialect();
    sql.name(column.name()).append(" " + dialect.type(definition, column));
    column.collation(dialect.name()).ifPresent(collation -> sql.append(" COLLATE ").name(collation));
    if (column.attribute(IdentityAttribute.class).isPresent()) {
      sql.append(" GENERATED BY DEFAULT AS IDENTITY");
    }
    if (!column.nullable()) {
      sql.append(" NOT NULL");
    }
    column.attribute(DefaultAttribute.class)
        .ifPresent(value -> sql.append(" DEFAULT " + dialect.defaultValue(column, value)));
  }
}
