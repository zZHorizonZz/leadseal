package dev.horizon.leadseal.command;

import dev.horizon.leadseal.Dialect;
import dev.horizon.leadseal.ScriptWriter;
import dev.horizon.leadseal.TableName;

/**
 * Makes the database generate the values of a column. The values start after the largest existing value.
 */
public class AddIdentityCommand extends Command {

  private final TableName table;
  private final String column;

  public AddIdentityCommand(TableName table, String column) {
    this.table = table;
    this.column = column;
  }

  /**
   * Returns the table.
   *
   * @return the table
   */
  public TableName table() {
    return table;
  }

  /**
   * Returns the column name.
   *
   * @return the column name
   */
  public String column() {
    return column;
  }

  @Override
  public void render(ScriptWriter sql) {
    sql.append("ALTER TABLE ").table(table).append(" ALTER COLUMN ").name(column)
        .append(" ADD GENERATED BY DEFAULT AS IDENTITY").end();
    Dialect dialect = sql.dialect();
    sql.append("SELECT setval(pg_get_serial_sequence(" + dialect.string(dialect.qualified(table)) + ", "
        + dialect.string(column)
        + "), COALESCE(MAX(").name(column).append("), 0) + 1, false) FROM ").table(table);
  }
}
