package dev.horizon.leadseal.command;

import dev.horizon.leadseal.Column;
import dev.horizon.leadseal.ScriptWriter;
import dev.horizon.leadseal.Table;
import dev.horizon.leadseal.attribute.Check;
import dev.horizon.leadseal.attribute.Default;
import dev.horizon.leadseal.attribute.ForeignKey;
import dev.horizon.leadseal.attribute.Generated;
import dev.horizon.leadseal.attribute.Identity;
import dev.horizon.leadseal.attribute.PrimaryKey;
import dev.horizon.leadseal.expression.SqlEnvironment;
import java.util.Optional;

/**
 * A part of a statement, such as the definition of a column in {@code CREATE TABLE}. A clause writes itself into the
 * statement that a {@link Command} writes, and ends no statement.
 */
@FunctionalInterface
public interface Clause {

  /**
   * Writes this clause.
   *
   * @param script the script of the statement
   */
  void write(ScriptWriter script);

  /**
   * The standard definition of a column: {@code name type [COLLATE c] [GENERATED BY DEFAULT AS IDENTITY] [NOT NULL]
   * [DEFAULT value]}, or {@code name type GENERATED ALWAYS AS (expression) STORED} for a generated column.
   *
   * @param table the table of the column
   * @param column the column
   */
  record ColumnDefinition(Table table, Column column) implements Clause {

    @Override
    public void write(ScriptWriter script) {
      script.name(column.name()).append(" " + script.dialect().type(table, column));
      Optional<Generated> generation = column.attribute(Generated.class);
      if (generation.isPresent()) {
        script.append(" GENERATED ALWAYS AS (" + generation.get().expression().value(SqlEnvironment.of(script
            .dialect())) + ") STORED");
        return;
      }
      column.collation(script.dialect().name()).ifPresent(collation -> script.append(" COLLATE ").name(collation));
      if (column.attribute(Identity.class).isPresent()) {
        script.append(" GENERATED BY DEFAULT AS IDENTITY");
      }
      if (!column.nullable()) {
        script.append(" NOT NULL");
      }
      column.attribute(Default.class)
          .ifPresent(value -> script.append(" DEFAULT " + script.dialect().defaultValue(column, value)));
    }
  }

  /**
   * A primary key: {@code CONSTRAINT name PRIMARY KEY (columns)}.
   *
   * @param key the primary key
   */
  record PrimaryKeyConstraint(PrimaryKey key) implements Clause {

    @Override
    public void write(ScriptWriter script) {
      script.append("CONSTRAINT ").name(key.name()).append(" PRIMARY KEY (").names(key.columns()).append(")");
    }
  }

  /**
   * A check: {@code CONSTRAINT name CHECK (condition)}.
   *
   * @param check the check
   */
  record CheckConstraint(Check check) implements Clause {

    @Override
    public void write(ScriptWriter script) {
      script.append("CONSTRAINT ").name(check.name()).append(" CHECK (" + check.expression() + ")");
    }
  }

  /**
   * A foreign key: {@code CONSTRAINT name FOREIGN KEY (columns) REFERENCES table (columns) [ON DELETE action]
   * [ON UPDATE action]}.
   *
   * @param key the foreign key
   */
  record ForeignKeyConstraint(ForeignKey key) implements Clause {

    @Override
    public void write(ScriptWriter script) {
      script.append("CONSTRAINT ").name(key.name()).append(" FOREIGN KEY (").names(key.columns())
          .append(") REFERENCES ").table(key.table()).append(" (").names(key.referencedColumns()).append(")")
          .append(key.onDelete().clause("ON DELETE")).append(key.onUpdate().clause("ON UPDATE"));
    }
  }
}
