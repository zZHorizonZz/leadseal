package dev.horizon.leadseal;

/**
 * The definition of a column in {@code CREATE TABLE} and {@code ADD COLUMN}: the quoted name, the database type, the
 * collation, the identity, {@code NOT NULL} and the default. Dialects decorate this node to write it in their order and
 * syntax.
 *
 * @param table the table of the column
 * @param column the column
 */
public record ColumnDefinition(Table table, Column column) implements Node {

  @Override
  public void render(DdlWriter sql) {
    sql.name(column.name()).append(" " + sql.dialect().type(table, column));
    String collation = column.collations().get(sql.dialect().name());
    if (collation != null) {
      sql.append(" COLLATE ").name(collation);
    }
    if (column.identity()) {
      sql.append(" GENERATED BY DEFAULT AS IDENTITY");
    }
    if (!column.nullable()) {
      sql.append(" NOT NULL");
    }
    if (column.defaultValue() != null) {
      sql.append(" DEFAULT " + sql.dialect().defaultValue(column));
    }
  }
}
